  var cache = null;

  function load() {
    if (cache) return cache;
    try {
      var raw = global.localStorage.getItem(KEY);
      if (raw) {
        var parsed = JSON.parse(raw);
        if (parsed && parsed.schema === SCHEMA) {
          cache = parsed;
          return cache;
        }
      }
    } catch (e) { /* ignore corrupted storage */ }
    cache = freshDB();
    save();
    return cache;
  }

  function save() {
    if (!cache) return;
    cache.updatedAt = new Date().toISOString();
    try {
      global.localStorage.setItem(KEY, JSON.stringify(cache));
    } catch (e) { /* storage may be full or blocked */ }
  }

  function reset() {
    cache = freshDB();
    save();
    return cache;
  }

  var seq = 0;
  function uid(prefix) {
    seq += 1;
    return (prefix || "id") + "-" + Date.now().toString(36) + "-" + seq;
  }

  global.DB = {
    KEY: KEY,
    load: load,
    save: save,
    reset: reset,
    uid: uid,
    projects: PROJECTS,
    list: function () { return load(); }
  };
